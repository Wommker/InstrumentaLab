'use strict';
const assert=require('node:assert/strict');
const listeners={};
const app={innerHTML:'',addEventListener(type,callback){listeners['app:'+type]=callback;}};
const tabs={addEventListener(type,callback){listeners['tabs:'+type]=callback;}};
const tabField={classList:{toggle(){}}};
const tabCreator={classList:{toggle(){}}};
const toast={textContent:'',classList:{add(){},remove(){}}};
global.document={
  getElementById(id){return ({app,toast,'tab-field':tabField,'tab-creator':tabCreator})[id];},
  querySelector(selector){return selector==='.mode-tabs'?tabs:null;}
};
global.localStorage={getItem(){return null;},setItem(){}};
require('../web/diagnostics.js');
require('../web/app.js');
const click=(where,action,extra={})=>listeners[where+':click']({target:{closest(){return {dataset:{action,...extra}};}}});
assert.match(app.innerHTML,/Sistemas críticos/);
assert.match(app.innerHTML,/data-action="open-system"/);
assert.match(app.innerHTML,/Sistema de lubricación/);
assert.match(app.innerHTML,/Variables de proceso/);
assert.match(app.innerHTML,/Sellos secos/);
assert.doesNotMatch(app.innerHTML,/Valor observado|Normal: <strong>/);
const systemId=app.innerHTML.match(/data-action="open-system" data-id="([^"]+)/)[1];
click('app','open-system',{id:systemId});
assert.match(app.innerHTML,/LI-101/);
assert.match(app.innerHTML,/0 \/ 5/);
assert.doesNotMatch(app.innerHTML,/Valor observado|Normal: <strong>/);
const variableId=app.innerHTML.match(/data-action="open-variable" data-id="([^"]+)/)[1];
click('app','open-variable',{id:variableId});
assert.match(app.innerHTML,/Valor observado/);
assert.match(app.innerHTML,/enterkeyhint="done"/);
assert.match(app.innerHTML,/Referencia oculta hasta registrar la lectura/);
assert.doesNotMatch(app.innerHTML,/Normal: <strong>/);
click('app','field-back');
assert.match(app.innerHTML,/LI-101/);
assert.doesNotMatch(app.innerHTML,/Valor observado/);
click('tabs','mode-creator');
assert.match(app.innerHTML,/Configurar equipo/);
assert.match(app.innerHTML,/Identificación del equipo/);
assert.doesNotMatch(app.innerHTML,/Valor normal/);
click('app','creator-view',{view:'systems'});
assert.match(app.innerHTML,/Sistemas y variables/);
assert.doesNotMatch(app.innerHTML,/Valor normal/);
const editorId=app.innerHTML.match(/data-action="select-editor-variable" data-id="([^"]+)/)[1];
click('app','select-editor-variable',{id:editorId});
assert.match(app.innerHTML,/Valor normal/);
click('app','creator-view',{view:'validation'});
assert.match(app.innerHTML,/Validar límites para campo/);
assert.doesNotMatch(app.innerHTML,/canvas|controlador|transmisor/i);
console.log('Interfaz compacta: navegación Campo/Creador y referencias ocultas correctas.');
